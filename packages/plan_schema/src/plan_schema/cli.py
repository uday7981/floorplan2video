"""CLI: export JSON Schema and TypeScript types from the Pydantic models.

  python -m plan_schema export-json-schema [--out plan_schema.json]
  python -m plan_schema export-ts          [--out apps/web/src/types/plan.ts]

JSON Schema is produced by Pydantic. The TS emitter is a tiny custom walker
(no npm/node dep required at this milestone). It handles the subset of JSON
Schema the plan uses: object with required/properties, enums, arrays, tuples,
$refs. If the schema ever grows beyond that, switch to json-schema-to-typescript
as a dev dep in apps/web.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from .models import Plan

DEFAULT_JSON_OUT = Path("packages/plan_schema/plan_schema.json")
DEFAULT_TS_OUT = Path("apps/web/src/types/plan.ts")

HEADER = (
    "// AUTO-GENERATED by `python -m plan_schema export-ts` — do not edit by hand.\n"
    "// Source of truth: packages/plan_schema (Pydantic v2 models).\n\n"
)


def _resolve_ref(root: dict, ref: str) -> dict:
    assert ref.startswith("#/"), f"only local refs supported, got {ref}"
    parts = ref[2:].split("/")
    cur: Any = root
    for p in parts:
        cur = cur[p]
    return cur


def _ts_type(schema: dict, root: dict, seen_refs: set[str]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        seen_refs.add(schema["$ref"])
        return name
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema or "oneOf" in schema:
        branches = schema.get("anyOf") or schema.get("oneOf") or []
        return " | ".join(_ts_type(b, root, seen_refs) for b in branches)
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = schema.get("items")
        # Tuple form (prefixItems) → fixed-length tuple.
        if isinstance(items, list):
            inner = ", ".join(_ts_type(i, root, seen_refs) for i in items)
            return f"[{inner}]"
        if "prefixItems" in schema:
            inner = ", ".join(_ts_type(i, root, seen_refs) for i in schema["prefixItems"])
            return f"[{inner}]"
        if isinstance(items, dict):
            return f"Array<{_ts_type(items, root, seen_refs)}>"
        return "unknown[]"
    if t == "object":
        return _ts_object(schema, root, seen_refs)
    return "unknown"


def _ts_object(schema: dict, root: dict, seen_refs: set[str]) -> str:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not props:
        return "Record<string, unknown>"
    lines = ["{"]
    for name, sub in props.items():
        opt = "" if name in required else "?"
        ts = _ts_type(sub, root, seen_refs)
        if desc := sub.get("description"):
            lines.append(f"  /** {desc} */")
        lines.append(f"  {name}{opt}: {ts};")
    lines.append("}")
    return "\n".join(lines)


def _emit_ts(schema: dict) -> str:
    """Walk the Plan's JSON Schema; emit one `export type` per $def."""
    defs = schema.get("$defs", {})
    seen_refs: set[str] = set()
    out: list[str] = [HEADER]

    # Emit $defs first.
    for name, sub in defs.items():
        if "enum" in sub:
            vals = " | ".join(json.dumps(v) for v in sub["enum"])
            out.append(f"export type {name} = {vals};\n")
        else:
            body = _ts_type(sub, schema, seen_refs)
            out.append(f"export type {name} = {body};\n")

    # Emit the root Plan type.
    body = _ts_type(schema, schema, seen_refs)
    out.append(f"export type Plan = {body};\n")

    return "\n".join(out)


def cmd_export_json_schema(args: argparse.Namespace) -> int:
    schema = Plan.model_json_schema()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(schema, indent=2) + "\n")
    print(f"wrote {out}  ({out.stat().st_size} bytes)")
    return 0


def cmd_export_ts(args: argparse.Namespace) -> int:
    schema = Plan.model_json_schema()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(_emit_ts(schema))
    print(f"wrote {out}  ({out.stat().st_size} bytes)")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="plan-schema")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_json = sub.add_parser("export-json-schema", help="write JSON Schema")
    p_json.add_argument("--out", default=str(DEFAULT_JSON_OUT))
    p_json.set_defaults(func=cmd_export_json_schema)

    p_ts = sub.add_parser("export-ts", help="write TypeScript types")
    p_ts.add_argument("--out", default=str(DEFAULT_TS_OUT))
    p_ts.set_defaults(func=cmd_export_ts)

    args = ap.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
